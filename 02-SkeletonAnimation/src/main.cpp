#define ARRAY_SIZE_IN_ELEMENTS(a) (sizeof(a)/sizeof(a[0]))

int screenWidth;
int screenHeight;

GLFWwindow *window;

//Shader con skybox
Shader shaderSkybox;
//Shader con multiples luces
Shader shaderMulLighting;

std::shared_ptr<FirstPersonCamera> camera(new FirstPersonCamera());

Sphere skyboxSphere(20, 20);
Box boxCesped;
Model IreliaModelAnimate;

GLuint textureCespedID;
GLuint skyboxTextureID;

GLenum types[6] = {
GL_TEXTURE_CUBE_MAP_POSITIVE_X,
GL_TEXTURE_CUBE_MAP_NEGATIVE_X,
GL_TEXTURE_CUBE_MAP_POSITIVE_Y,
GL_TEXTURE_CUBE_MAP_NEGATIVE_Y,
GL_TEXTURE_CUBE_MAP_POSITIVE_Z,
GL_TEXTURE_CUBE_MAP_NEGATIVE_Z };

std::string fileNames[6] = {
    "../Textures/clouds1/clouds1_east.bmp",
    "../Textures/clouds1/clouds1_west.bmp",
    "../Textures/clouds1/clouds1_up.bmp",
    "../Textures/clouds1/clouds1_down.bmp",
    "../Textures/clouds1/clouds1_north.bmp",
    "../Textures/clouds1/clouds1_south.bmp"
};

bool exitApp = false;
int lastMousePosX, offsetX = 0;
int lastMousePosY, offsetY = 0;

// Estado de Irelia: animacion 0 al moverse, 1 en reposo.
glm::mat4 modelMatrixIrelia = glm::mat4(1.0f);
int animationIndexIrelia = 1;

double deltaTime;
double currTime, lastTime;

// Se definen todos las funciones.
